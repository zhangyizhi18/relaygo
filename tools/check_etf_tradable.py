def parse_pool(text):
    codes = []
    for line in text.splitlines():
        s = line.strip()
        if s.startswith('#'):
            continue
        m = re.search(r"'(\d{6}\.XS[A-Z]{2})'", line)
        if m:
            codes.append(m.group(1))
    return codes


def qname(code):
    return 'sh' + code[:6] if code.endswith('XSHG') else 'sz' + code[:6]


def list_date(code, raw):
    # 从注释里抓 上市日期
    for line in raw.splitlines():
        if ("'%s'" % code) in line and '上市日期' in line:
            m = re.search(r'上市日期：(\d{4}-\d{2}-\d{2})', line)
            if m:
                return m.group(1)
    return ''


def extract_block(raw, marker):
    i = raw.index(marker)
    j = raw.index('[', i)
    lines = raw[j:].splitlines()
    for k, line in enumerate(lines):
        if line.strip() == ']' and k > 0:
            return '\n'.join(lines[1:k])
    return raw[j:]


g1 = extract_block(RAW, 'g.global_etf_pool = [')
g2 = extract_block(RAW, 'g.china_etf_pool = [')
global_pool = parse_pool(g1)
china_pool = parse_pool(g2)

all_codes = list(dict.fromkeys(global_pool + china_pool))  # 去重保序

info = {}  # code -> (name, price, time, flag)
for i in range(0, len(all_codes), 40):
    batch = all_codes[i:i + 40]
    url = 'https://qt.gtimg.cn/q=' + ','.join(qname(c) for c in batch)
    try:
        r = requests.get(url, timeout=15)
    except Exception as e:
        for c in batch:
            info[c] = ('', '', '', '请求异常:%s' % e)
        continue
    r.encoding = 'gbk'
    for c in batch:
        m = re.search(r'v_%s="([^"]*)"' % qname(c), r.text)
        if not m or not m.group(1):
            info[c] = ('', '', '', '无数据')
            continue
        f = m.group(1).split('~')
        name = f[1] if len(f) > 1 else ''
        price = f[3] if len(f) > 3 else ''
        t = f[30] if len(f) > 30 else ''
        raw = m.group(1)
        flag = ''
        if '停牌' in raw or '暂停' in raw:
            flag = '停牌/暂停'
        info[c] = (name, price, t, flag)

EXCLUDED = {}  # code -> reason
for c in all_codes:
    name, price, t, flag = info.get(c, ('', '', '', ''))
    if not name:
        EXCLUDED[c] = '获取不到名称/代码不存在'
    elif flag:
        EXCLUDED[c] = flag
    else:
        try:
            if float(price or 0) <= 0:
                EXCLUDED[c] = '获取不到价格(price=%s)' % price
        except ValueError:
            EXCLUDED[c] = '价格非法(%s)' % price

